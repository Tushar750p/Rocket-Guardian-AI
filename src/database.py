def create_customer(name, email):
    connection = get_connection()

    try:
        cursor = connection.cursor()

        if using_postgres():
            cursor.execute(
                """
                INSERT INTO customers (name, email)
                VALUES (?, ?)
                RETURNING id
                """,
                (name, email),
            )
            row = cursor.fetchone()
            connection.commit()
            return int(row["id"])

        cursor.execute(
            """
            INSERT INTO customers (name, email)
            VALUES (?, ?)
            """,
            (name, email),
        )
        connection.commit()
        return int(cursor.lastrowid)

    finally:
        connection.close()


