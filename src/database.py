# ============================================================
# FIND TELEMETRY RUN
# ============================================================

def find_telemetry_run(
    source_filename,
    customer_id,
    mission_name,
):
    connection = get_connection()

    try:
        cursor = connection.cursor()

        cursor.execute(
            """
            SELECT
                tr.id
            FROM telemetry_runs tr
            JOIN missions m
                ON tr.mission_id = m.id
            WHERE tr.source_filename = ?
            AND m.customer_id = ?
            AND m.name = ?
            ORDER BY tr.id DESC
            LIMIT 1
            """,
            (
                source_filename,
                customer_id,
                mission_name,
            ),
        )

        return cursor.fetchone()

    finally:
        connection.close()


